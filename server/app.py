import json
import os
import secrets
import sqlite3
import hmac
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

from fastapi import FastAPI, HTTPException, Header, Depends
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get('MEETUP_DATA_DIR', str(ROOT / 'data')))
DATABASE_URL = os.environ.get('DATABASE_URL', '').strip()
ADMIN_TOKEN = os.environ.get('MEETUP_ADMIN_TOKEN', '')

# Local development uses SQLite. Render uses PostgreSQL when DATABASE_URL is supplied.
if not DATABASE_URL:
    DATA.mkdir(parents=True, exist_ok=True)
    DB = DATA / 'meetups.sqlite3'
else:
    import psycopg
    from psycopg.rows import dict_row

app = FastAPI(title='Meetup Protocol API', docs_url=None, redoc_url=None)

@contextmanager
def db():
    if DATABASE_URL:
        # psycopg handles commit on successful exit and rollback on exception.
        with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as conn:
            yield conn
    else:
        conn = sqlite3.connect(DB, timeout=10)
        conn.row_factory = sqlite3.Row
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

def sql(sqlite_sql: str) -> str:
    """Translate SQLite positional placeholders to psycopg placeholders."""
    return sqlite_sql.replace('?', '%s') if DATABASE_URL else sqlite_sql

def initialize_database():
    with db() as con:
        if DATABASE_URL:
            con.execute('''CREATE TABLE IF NOT EXISTS invitations (
                id TEXT PRIMARY KEY,
                title TEXT NOT NULL,
                config TEXT NOT NULL,
                created_at TEXT NOT NULL
            )''')
            con.execute('''CREATE TABLE IF NOT EXISTS responses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                invitation_id TEXT NOT NULL REFERENCES invitations(id),
                status TEXT NOT NULL,
                date TEXT,
                time TEXT,
                activity TEXT,
                note TEXT,
                created_at TEXT NOT NULL
            )''')
        else:
            con.execute('PRAGMA journal_mode=WAL')
            con.execute('CREATE TABLE IF NOT EXISTS invitations (id TEXT PRIMARY KEY, title TEXT NOT NULL, config TEXT NOT NULL, created_at TEXT NOT NULL)')
            con.execute('CREATE TABLE IF NOT EXISTS responses (id INTEGER PRIMARY KEY AUTOINCREMENT, invitation_id TEXT NOT NULL, status TEXT NOT NULL, date TEXT, time TEXT, activity TEXT, note TEXT, created_at TEXT NOT NULL, FOREIGN KEY(invitation_id) REFERENCES invitations(id))')

# FastAPI startup avoids attempting to connect to Render when the file is imported by tooling.
@app.on_event('startup')
def on_startup():
    initialize_database()

class Invite(BaseModel):
    title: str = Field(min_length=1, max_length=100)
    config: dict

class Response(BaseModel):
    status: str
    date: str | None = None
    time: str | None = None
    activity: str | None = None
    note: str | None = Field(default=None, max_length=240)

def admin(authorization: str | None = Header(None)):
    if not ADMIN_TOKEN:
        raise HTTPException(503, 'Server admin token is not configured')
    token = (authorization or '').removeprefix('Bearer ').strip()
    if not hmac.compare_digest(token, ADMIN_TOKEN):
        raise HTTPException(401, 'Invalid admin token')

@app.get('/api/health')
def health():
    return {'status': 'ok'}

@app.get('/api/invitations', dependencies=[Depends(admin)])
def list_invites():
    with db() as con:
        rows = con.execute('SELECT id,title,created_at FROM invitations ORDER BY created_at DESC').fetchall()
        return [dict(row) for row in rows]

@app.post('/api/invitations', dependencies=[Depends(admin)])
def make_invite(item: Invite):
    code = secrets.token_urlsafe(9)
    with db() as con:
        con.execute(sql('INSERT INTO invitations (id,title,config,created_at) VALUES (?,?,?,?)'),
                    (code, item.title, json.dumps(item.config), datetime.now(timezone.utc).isoformat()))
    return {'id': code, 'url': f'/i/{code}'}

@app.get('/api/invitations/{code}')
def get_invite(code: str):
    with db() as con:
        row = con.execute(sql('SELECT id,title,config FROM invitations WHERE id=?'), (code,)).fetchone()
    if not row:
        raise HTTPException(404, 'Invitation not found')
    return {'id': row['id'], 'title': row['title'], 'config': json.loads(row['config'])}

@app.put('/api/invitations/{code}', dependencies=[Depends(admin)])
def update_invite(code: str, item: Invite):
    with db() as con:
        cur = con.execute(sql('UPDATE invitations SET title=?,config=? WHERE id=?'),
                          (item.title, json.dumps(item.config), code))
        if not cur.rowcount:
            raise HTTPException(404, 'Invitation not found')
    return {'ok': True}

@app.delete('/api/invitations/{code}', dependencies=[Depends(admin)])
def delete_invite(code: str):
    with db() as con:
        con.execute(sql('DELETE FROM responses WHERE invitation_id=?'), (code,))
        con.execute(sql('DELETE FROM invitations WHERE id=?'), (code,))
    return {'ok': True}

@app.post('/api/invitations/{code}/responses')
def submit_response(code: str, item: Response):
    if item.status not in ('accepted', 'declined'):
        raise HTTPException(422, 'Invalid status')
    if item.status == 'accepted':
        if not (item.date and item.time and item.activity):
            raise HTTPException(422, 'Missing meeting preferences')
        try:
            datetime.strptime(item.date, '%Y-%m-%d')
            datetime.strptime(item.time, '%H:%M')
        except ValueError:
            raise HTTPException(422, 'Invalid date or time')

    with db() as con:
        if not con.execute(sql('SELECT 1 FROM invitations WHERE id=?'), (code,)).fetchone():
            raise HTTPException(404, 'Invitation not found')
        values = (code, item.status,
                  item.date if item.status == 'accepted' else None,
                  item.time if item.status == 'accepted' else None,
                  item.activity if item.status == 'accepted' else None,
                  item.note if item.status == 'accepted' else None,
                  datetime.now(timezone.utc).isoformat())
        query = sql('INSERT INTO responses(invitation_id,status,date,time,activity,note,created_at) VALUES(?,?,?,?,?,?,?)')
        if DATABASE_URL:
            inserted = con.execute(query + ' RETURNING id', values).fetchone()
            response_id = inserted['id']
        else:
            cur = con.execute(query, values)
            response_id = cur.lastrowid
    return {'ok': True, 'responseId': response_id}

@app.get('/api/invitations/{code}/responses', dependencies=[Depends(admin)])
def list_responses(code: str):
    with db() as con:
        rows = con.execute(sql('SELECT id,status,date,time,activity,note,created_at FROM responses WHERE invitation_id=? ORDER BY id DESC'), (code,)).fetchall()
        return [dict(row) for row in rows]

